/**
 * Embed Indiekonnect's original logo PNG in src/utils/invoiceLogoData.ts.
 * Usage:
 *   node scripts/embed-invoice-logo.mjs
 *   node scripts/embed-invoice-logo.mjs ./Downloads/logo.png
 * No npm packages required; Node.js 18+.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve, dirname } from "node:path";

const OFFICIAL_URL =
  "https://www.markupdesigns.net/indikonnect/storage/logos/MmVFOudCiVU3Y8C0sf2gEEXna5jSKroCDj8xYMo0.png";
const OUTPUT = resolve(process.cwd(), "src/utils/invoiceLogoData.ts");

async function main() {
  let bytes;
  if (process.argv[2]) {
    const input = resolve(process.argv[2]);
    bytes = await readFile(input);
    console.log(`Reading original PNG: ${input}`);
  } else {
    console.log(`Fetching original Indiekonnect logo: ${OFFICIAL_URL}`);
    const response = await fetch(OFFICIAL_URL, {
      headers: {
        Accept: "image/png,image/*;q=0.8",
        "User-Agent": "Mozilla/5.0 InvoiceLogoBuild/1.0",
      },
      signal: AbortSignal.timeout(20000),
    });
    if (!response.ok)
      throw new Error(`Image request failed: HTTP ${response.status}`);
    bytes = Buffer.from(await response.arrayBuffer());
  }

  // Validate binary PNG data instead of embedding an HTML error document.
  const PNG_MAGIC = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
  if (bytes.length < 24 || !bytes.subarray(0, 8).equals(PNG_MAGIC)) {
    throw new Error(
      "Downloaded file is not a PNG. Open the logo URL in a browser and save the PNG, then pass the saved path to this script.",
    );
  }
  if (bytes.length > 5 * 1024 * 1024) {
    throw new Error(
      "The PNG is larger than 5 MB. Please optimize it before embedding.",
    );
  }
  const width = bytes.readUInt32BE(16);
  const height = bytes.readUInt32BE(20);
  if (!width || !height || width > 10000 || height > 10000) {
    throw new Error("PNG dimensions appear invalid.");
  }
  const dataUri = `data:image/png;base64,${bytes.toString("base64")}`;
  const moduleSource = [
    "// AUTO-GENERATED by scripts/embed-invoice-logo.mjs. Do not hand-edit.",
    "// Original source: " + OFFICIAL_URL,
    `export const INVOICE_LOGO_DATA_URL = ${JSON.stringify(dataUri)};`,
    `export const INVOICE_LOGO_WIDTH = ${width};`,
    `export const INVOICE_LOGO_HEIGHT = ${height};`,
    "",
  ].join("\n");
  await mkdir(dirname(OUTPUT), { recursive: true });
  await writeFile(OUTPUT, moduleSource, "utf8");
  console.log(`SUCCESS: Embedded ${width}x${height} PNG into ${OUTPUT}`);
  console.log("Commit src/utils/invoiceLogoData.ts and rebuild your app.");
}

main().catch((error) => {
  console.error("ERROR: Could not embed the invoice logo:", error.message);
  console.error("If fetching fails, save the image from the URL and run:");
  console.error(
    "node scripts/embed-invoice-logo.mjs ./path/to/downloaded-logo.png",
  );
  process.exitCode = 1;
});
